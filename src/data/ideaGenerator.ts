export function generateIdea(toneId: string, lastIdea: Idea | null): Idea {
  const pool = ideas[toneId] ?? ideas.motivational;
  let idea = pool[Math.floor(Math.random() * pool.length)];
  if (lastIdea && pool.length > 1) {
    let attempts = 0;
    while (idea.title === lastIdea.title && attempts < 10) {
      idea = pool[Math.floor(Math.random() * pool.length)];
      attempts++;
    }
  }
  return idea;
}

export function generateMultipleIdeas(toneId: string, count: number): Idea[] {
  const pool = ideas[toneId] ?? ideas.motivational;
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, pool.length));
}

